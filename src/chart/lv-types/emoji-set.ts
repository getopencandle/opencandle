/** The emoji text of a code point. */
export const emojiOf=(codePoint:number)=>String.fromCodePoint(codePoint);
/** Every listed emoji glyph, in list order. */
export const EMOJI_GLYPHS:readonly string[]=Object.freeze(EMOJI_GROUPS.flatMap(row=>row.codePoints.map(emojiOf)));
/** The emoji a new stamp gets before anything is picked: the first listed entry (OpenCandle choice; the reference
 *  default emoji of this tool is not recorded). */
export const DEFAULT_EMOJI=EMOJI_GLYPHS[0];

/** static-drawing-toolbar#group.linetool-group-font-icons recentsMax. */
export const EMOJI_RECENTS_MAX=18;
/** visual-dialogs-drawing-flyouts#flyout.linetool-group-font-icons: rows of 9 cells. */
export const EMOJI_GRID_COLUMNS=9;
/** visual-dialogs-drawing-flyouts#flyout.linetool-group-font-icons: cells 37x38, category buttons 38x38. */
export const EMOJI_CELL_PX=Object.freeze({width:37,height:38});
export const EMOJI_CATEGORY_BUTTON_PX=Object.freeze({width:38,height:38});
/** static-drawing-toolbar#group.linetool-group-font-icons menuMaxHeightPx. */
export const EMOJI_MENU_MAX_HEIGHT_PX=679;

/** System emoji fonts (Windows, macOS, Linux/ChromeOS), then the CSS emoji generic family; no bundled emoji images. */
export const EMOJI_FONT_FAMILY='"Segoe UI Emoji", "Apple Color Emoji", "Noto Color Emoji", emoji, sans-serif';

/** Splits a list into grid rows of EMOJI_GRID_COLUMNS. */
export function emojiRows<T>(items:readonly T[],columns=EMOJI_GRID_COLUMNS):T[][]{
 const rows:T[][]=[];for(let i=0;i<items.length;i+=columns)rows.push(items.slice(i,i+columns));return rows;
}
/** Most recent first, no duplicates, at most EMOJI_RECENTS_MAX. */
export function pushRecentEmoji(recents:readonly string[],glyph:string,max=EMOJI_RECENTS_MAX):string[]{
 return [glyph,...recents.filter(item=>item!==glyph)].slice(0,max);
}

// Picker selection (one per app session): the emoji the next placed Emojis stamp gets, and the recents row.
// Kept in memory only; persisting recents across sessions is a host (workspace) decision.
let selected=DEFAULT_EMOJI;
let recents:string[]=[];
const listeners=new Set<()=>void>();
export const selectedEmoji=()=>selected;
export const recentEmojis=():readonly string[]=>recents;
/** Picks `glyph` for the next stamp and records it as recently used. Returns false for an empty value. */
export function pickEmoji(glyph:string):boolean{
 if(typeof glyph!=='string'||!glyph.trim())return false;
 selected=glyph;recents=pushRecentEmoji(recents,glyph);
 for(const listener of [...listeners])listener();
 return true;
}
export function onEmojiPicked(listener:()=>void):()=>void{listeners.add(listener);return()=>{listeners.delete(listener);};}
/** Test and workspace-reset hook: back to the default emoji and no recents. */
export function resetEmojiPicker(){selected=DEFAULT_EMOJI;recents=[];for(const listener of [...listeners])listener();}
