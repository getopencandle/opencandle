import { describe, it, expect } from 'vitest';
import { identifyDisplayBars, LosslessDrawingDocument, requireVolume } from '../../src/chart/contracts';
import { mapAppearance } from '../../src/chart/appearance';

describe('OpenCandle chart boundary contracts',()=>{
  it('preserves distinct bars generated by the same source event',()=>{
    const bar={time:1700000000,open:10,high:12,low:10,close:12,volume:100};
    const rows=identifyDisplayBars([bar,bar],{datasetId:'synthetic-topology',revision:'r1',transformId:'renko-2'},[[7,7],[7,7]]);
    expect(new Set(rows.map(row=>row.id)).size).toBe(2);
    expect(rows.map(row=>row.logicalIndex)).toEqual([0,1]);
    expect(rows.map(row=>row.sourceTime)).toEqual([1700000000,1700000000]);
    expect(rows[1].identity.sourceFirstSequence).toBe(7);
  });
  it('retains opaque unsupported drawings and future document fields across render updates and undo',()=>{
    const original={version:1,extension:{future:true},drawings:[{id:'future',type:'future-pattern',props:{opaque:{v:[1,2,3]}}},{id:'known',type:'trendline',custom:99,style:{color:'red',futureStyle:123},props:{future:{x:1}}}]};
    const store=new LosslessDrawingDocument();store.load(original);
    store.mergeRenderable([{id:'known',type:'trendline',style:{color:'blue'}}],new Set(['trendline']));
    expect(store.all().find(row=>row.id==='future')).toEqual(original.drawings[0]);
    expect(store.all().find(row=>row.id==='known')?.custom).toBe(99);
    expect(store.all().find(row=>row.id==='known')?.style).toEqual({color:'blue',futureStyle:123});
    expect(store.all().find(row=>row.id==='known')?.props).toEqual({future:{x:1}});
    expect(store.diagnostics(new Set(['trendline']))[0].code).toBe('DRAWING_RENDERER_UNAVAILABLE');
    expect(store.undo()).toBe(true);expect(store.serialize()).toEqual(original);
    expect(store.redo()).toBe(true);expect(store.serialize().extension).toEqual({future:true});
  });
  it('does not coerce unavailable volume to zero',()=>{
    const absent={time:1,open:1,high:2,low:1,close:2,volume:NaN};
    expect(requireVolume([absent],'anchored-vwap')).toMatchObject({ok:false,diagnostic:{code:'DATA_VOLUME_UNAVAILABLE'}});
    expect(requireVolume([{...absent,volume:0}],'anchored-vwap').ok).toBe(true);
  });
  it('uses the independent the reference app LineStyle enum: solid0 dotted1 dashed2',()=>{
    for(const [input,expected] of [[0,'solid'],[1,'dotted'],[2,'dashed']] as const){
      const result=mapAppearance({'paneProperties.crossHairProperties.style':String(input)});
      expect(result.config.crosshair).toMatchObject({style:expected});
    }
  });
  it('retains disabled gradient and alpha settings; reports active unsupported settings',()=>{
    const settings={'paneProperties.backgroundType':'solid','paneProperties.backgroundGradientStartColor':'rgba(1, 2, 3, 0.25)','paneProperties.backgroundGradientEndColor':'#040506','paneProperties.vertGridProperties.color':'rgba(7, 8, 9, 0.4)','mainSeriesProperties.candleStyle.barColorsOnPrevClose':true};
    const result=mapAppearance(settings);
    expect(result.retainedSettings).toEqual(settings);
    expect(result.config.grid).toMatchObject({vertLines:{color:'rgba(7, 8, 9, 0.4)'}});
    expect(result.diagnostics.some(row=>row.feature==='mainSeriesProperties.candleStyle.barColorsOnPrevClose')).toBe(true);
    expect(result.diagnostics.some(row=>row.feature==='paneProperties.backgroundType')).toBe(false);
  });
});
