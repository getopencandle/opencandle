import {describe,expect,it} from 'vitest';
import type {LineLikeSeries} from '@luxalgo/vela';
import {calculateIndicator,type IndicatorResult} from '../../src/domain/indicators';
import type {Bar} from '../../src/domain/types';
import {defaultIndicatorPresentation,indicatorDefaults,indicatorLegacyDefaults,type IndicatorInstanceSettings} from '../../src/chart/indicator-settings';
import {renderIndicatorPresentation} from '../../src/chart/indicator-presentation';

// Synthetic arithmetic inputs only. These tests inspect the actual presentation path;
// numerical band expectations below are hand-calculated, not generated by that path.
const source=(values:number[]):Bar[]=>values.map((close,index)=>({time:1704153600+index*60,open:close,high:close,low:close,close,volume:10+index}));
const bars=source(Array.from({length:40},(_,index)=>20+index%7));
const smoothingKinds=['sma','ema','rsi','obv'] as const;
const settings=(kind:IndicatorInstanceSettings['kind']):IndicatorInstanceSettings=>({id:'review-'+kind,kind,inputs:{...indicatorDefaults[kind]},plots:{},offset:0,visible:true,presentation:defaultIndicatorPresentation(kind)});
const smoothingFills=(value:ReturnType<typeof renderIndicatorPresentation>)=>value.output.fills!.filter(fill=>fill.id.includes('fill:smoothing'));
const bandSettings=()=>{const value=settings('sma');value.inputs={length:1,source:'close',smoothingType:'SMA+BB',smoothingLength:2,smoothingMultiplier:2};return value;};

describe('inactive smoothing is distinct from unavailable active boundaries',()=>{
 it('factory SMA, EMA, RSI and OBV retain their visible saved fill styles without a false warning',()=>{
  for(const kind of smoothingKinds){
   const saved=settings(kind),before=JSON.stringify(saved),result=calculateIndicator(kind,bars,saved.inputs),numericalBefore=JSON.stringify(result);
   expect(saved.inputs.smoothingType).toBe('None');expect(saved.presentation!.fills.smoothing!.visible).toBe(true);
   const rendered=renderIndicatorPresentation(saved,result,bars);
   expect(rendered.diagnostics,kind).toEqual([]);expect(smoothingFills(rendered),kind).toEqual([]);
   expect(JSON.stringify(saved),kind).toBe(before);expect(JSON.stringify(result),kind).toBe(numericalBefore);
   // RSI's separate fixed 30..70 band remains rendered while smoothing is inactive.
   expect(rendered.output.fills!.length,kind).toBe(kind==='rsi'?1:0);
  }
 });
 it('omitted legacy smoothing inputs also leave the add-on inactive without rewriting the saved settings',()=>{
  for(const kind of smoothingKinds){const saved=settings(kind);saved.inputs={...indicatorLegacyDefaults[kind]};const before=JSON.stringify(saved);
   const rendered=renderIndicatorPresentation(saved,calculateIndicator(kind,bars,saved.inputs),bars);
   expect(rendered.diagnostics,kind).toEqual([]);expect(smoothingFills(rendered),kind).toEqual([]);expect(JSON.stringify(saved),kind).toBe(before);
  }
 });
 it('None and every non-band smoothing method omit only the smoothing fill',()=>{
  for(const kind of smoothingKinds)for(const method of ['None','SMA','EMA','RMA','WMA','VWMA']){
   const saved=settings(kind);saved.inputs.smoothingType=method;const result=calculateIndicator(kind,bars,saved.inputs),rendered=renderIndicatorPresentation(saved,result,bars);
   expect(result.plotDiagnostics,kind+' '+method).toBeUndefined();expect(rendered.diagnostics,kind+' '+method).toEqual([]);expect(smoothingFills(rendered),kind+' '+method).toEqual([]);
   expect(result.series.some(plot=>plot.id==='smooth'),kind+' '+method).toBe(method!=='None');
  }
 });
 it('active SMA+BB preserves literal population bands, warmup gaps, times and readout isolation',()=>{
  const supplied=source([3,9,6,12]),saved=bandSettings(),result=calculateIndicator('sma',supplied,saved.inputs),before=JSON.stringify(result),rendered=renderIndicatorPresentation(saved,result,supplied);
  expect(rendered.diagnostics).toEqual([]);expect(smoothingFills(rendered)).toHaveLength(1);
  const fill=smoothingFills(rendered)[0],all=rendered.output.series! as LineLikeSeries[],lower=all.find(row=>row.id===fill.fromSeriesId)!,upper=all.find(row=>row.id===fill.toSeriesId)!;
  // Pairs (3,9), (9,6), (6,12): means 6,7.5,9; population deviations 3,1.5,3.
  expect(lower.points.map(point=>point.value)).toEqual([null,0,4.5,3]);expect(upper.points.map(point=>point.value)).toEqual([null,12,10.5,15]);
  expect(lower.points.map(point=>point.time)).toEqual([1704153600000,1704153660000,1704153720000,1704153780000]);
  expect(lower.display).toEqual({pane:true,priceScale:false,legend:false,dataWindow:false});expect(upper.display).toEqual(lower.display);
  expect(JSON.stringify(result)).toBe(before);
 });
 it('active SMA+BB still reports each missing boundary instead of drawing a partial fill',()=>{
  const saved=bandSettings(),supplied=source([3,9,6,12]),complete=calculateIndicator('sma',supplied,saved.inputs);
  for(const absent of ['smoothLower','smoothUpper']){
   const incomplete:IndicatorResult={...complete,series:complete.series.filter(plot=>plot.id!==absent)},before=JSON.stringify(incomplete),rendered=renderIndicatorPresentation(saved,incomplete,supplied);
   expect(rendered.diagnostics,absent).toEqual(['smoothing fill is unavailable because its required boundaries are absent or unavailable.']);
   expect(smoothingFills(rendered),absent).toEqual([]);expect(JSON.stringify(incomplete),absent).toBe(before);
  }
 });
 it('active SMA+BB keeps boundary diagnostics authoritative even when finite values are supplied',()=>{
  const saved=bandSettings(),supplied=source([3,9,6,12]),complete=calculateIndicator('sma',supplied,saved.inputs);
  for(const unavailable of ['smoothLower','smoothUpper']){
   const result={...complete,plotDiagnostics:{[unavailable]:['Boundary is unavailable in this controlled result.']}},rendered=renderIndicatorPresentation(saved,result,supplied);
   expect(rendered.diagnostics,unavailable).toEqual(['smoothing fill is unavailable because its required boundaries are absent or unavailable.']);expect(smoothingFills(rendered),unavailable).toEqual([]);
   expect(result.plotDiagnostics[unavailable]).toEqual(['Boundary is unavailable in this controlled result.']);
  }
 });
 it('legitimate all-null warmup boundaries remain present rather than being diagnosed as missing',()=>{
  const saved=bandSettings(),supplied=source([3]),result=calculateIndicator('sma',supplied,saved.inputs),rendered=renderIndicatorPresentation(saved,result,supplied);
  expect(rendered.diagnostics).toEqual([]);expect(smoothingFills(rendered)).toHaveLength(1);
  const fill=smoothingFills(rendered)[0],all=rendered.output.series! as LineLikeSeries[];
  expect(all.find(row=>row.id===fill.fromSeriesId)!.points.map(point=>point.value)).toEqual([null]);expect(all.find(row=>row.id===fill.toSeriesId)!.points.map(point=>point.value)).toEqual([null]);
 });
 it('turning bands off and back on retains their saved presentation without inactive warnings',()=>{
  const saved=bandSettings(),styleBefore=JSON.stringify(saved.presentation),supplied=source([3,9,6,12]);
  for(const method of ['SMA+BB','EMA','None','SMA+BB']){saved.inputs.smoothingType=method;const rendered=renderIndicatorPresentation(saved,calculateIndicator('sma',supplied,saved.inputs),supplied);
   expect(rendered.diagnostics,method).toEqual([]);expect(smoothingFills(rendered).length,method).toBe(method==='SMA+BB'?1:0);expect(JSON.stringify(saved.presentation),method).toBe(styleBefore);
  }
 });
 it('ordinary Bollinger missing boundaries still warn independently of optional smoothing',()=>{
  const saved=settings('bb'),result:IndicatorResult={id:'bb',series:[{id:'basis',label:'Basis',values:bars.map(()=>5)},{id:'upper',label:'Upper',values:bars.map(()=>7)}],diagnostics:[],policies:[]};
  const rendered=renderIndicatorPresentation(saved,result,bars);expect(rendered.diagnostics).toEqual(['band fill is unavailable because its required boundaries are absent or unavailable.']);expect(rendered.output.fills).toEqual([]);
 });
 it('a user-hidden active fill stays hidden without requiring otherwise unused boundaries',()=>{
  const saved=bandSettings();saved.presentation!.fills.smoothing!.visible=false;
  const result:IndicatorResult={id:'sma',series:[{id:'sma',label:'SMA',values:bars.map(()=>5)}],diagnostics:[],policies:[]},rendered=renderIndicatorPresentation(saved,result,bars);
  expect(rendered.diagnostics).toEqual([]);expect(rendered.output.fills).toEqual([]);expect(saved.inputs.smoothingType).toBe('SMA+BB');
 });
 it('real calculation overflow in enabled smoothing bands remains an unavailable-fill warning',()=>{
  const saved=bandSettings();saved.inputs.smoothingMultiplier=100000;const supplied=source([1e304,2e304]),result=calculateIndicator('sma',supplied,saved.inputs),rendered=renderIndicatorPresentation(saved,result,supplied);
  expect(result.plotDiagnostics?.smoothLower?.[0]).toMatch(/overflow/i);expect(result.plotDiagnostics?.smoothUpper?.[0]).toMatch(/overflow/i);
  expect(rendered.diagnostics).toEqual(['smoothing fill is unavailable because its required boundaries are absent or unavailable.']);expect(smoothingFills(rendered)).toEqual([]);
 });
});
