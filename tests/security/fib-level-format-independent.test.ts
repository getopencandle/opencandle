type Fib=ReturnType<typeof deserializeDrawing>&{levelText(ratio:number,price:number):string;entryLines(projection:unknown):any[];showRatios:boolean;showPrices:boolean};
function fib(format?:unknown,present=false):SerializedDrawing{
 const row=createDrawing('fibretracement',{id:'SYNTHETIC independent Fib format',paneId:'price',zIndex:4,anchors:[{time:1000000,price:100},{time:1240000,price:200}]})!.serialize();
 row.props={...row.props,reverse:false,showRatios:true,showPrices:true,background:true,levels:[
  {ratio:.236,color:'rgba(61,142,219,0.35)',enabled:true,label:'SYNTHETIC first'},
  {ratio:.382,color:'#ff0000',enabled:false,label:'SYNTHETIC disabled'},
  {ratio:.618,color:'#00ff00',enabled:true,label:'SYNTHETIC second'},
 ]};
 delete row.props[field];if(present)row.props[field]=format;
 return row;
}
function model(row:SerializedDrawing):Fib{return deserializeDrawing(row)! as Fib;}
function words(commands:any[]){return commands.filter(command=>command.op==='fillText'&&command.values[0]!=='').map(command=>command.values[0]);}

